#!/usr/bin/env python3
"""Write art/_village.scene: the village the outdoor stills share.

FishE and Tidewater are set in the same fishing village, so this file and its
output are kept identical to Tidewater's
(https://github.com/Stephenson-Software/Tidewater, art/): change both together.

    python3 art/gen_village.py

The land is one Strata terrain tile whose heights come from the function
below - a strip of shore, a hill rising north to the church, a headland to the
west for the lighthouse - and whose heights below zero are under the
harbour's water. Houses, the pier, the bell tower, the church and the
lighthouse are written as items and roof meshes. Strata's world has -Z north
and +X east; the harbour opens south. Re-run after editing; the output is
committed alongside it.
"""

import math
import os
import random

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_village.scene")
X0, Z0, CELL, NX, NZ = -150.0, -130.0, 5.0, 61, 49  # x -150..150, z -130..110


def height(x, z):
    """Metres above the water: shore, hill, headland."""
    land = 1.2 - max(0.0, z - 16.0) * 0.5  # the front, dropping into the harbour
    hill = max(0.0, -z - 15.0) * 0.16  # rising north behind the village
    hill += 4.0 * math.exp(-(((x - 35.0) / 30.0) ** 2 + ((z + 55.0) / 22.0) ** 2))
    head = 11.0 * math.exp(-(((x + 85.0) / 26.0) ** 2 + ((z - 50.0) / 30.0) ** 2))
    return max(land, -4.0) + hill + head


def colour(h, x, z, rng):
    if h < 0.2:
        return (0.42, 0.40, 0.33)  # wet sand and shingle under the water line
    if h < 1.6 and z > 8:
        return (0.62, 0.58, 0.46)  # the front
    if h > 8 and x < -60:
        return (0.45, 0.47, 0.40)  # bare rock on the headland
    g = rng.uniform(0.9, 1.1)
    return (0.24 * g, 0.42 * g, 0.18 * g)


def gable(x0, x1, z0, z1, eave, rise, wall, roof, base=0.0):
    """A house: walls as a box, a roof prism ridged along x."""
    zc = (z0 + z1) / 2
    lines = [
        "item cube %.2f %.2f %.2f  %.2f %.2f %.2f  %s"
        % ((x0 + x1) / 2, base + eave / 2, zc, x1 - x0, eave, z1 - z0, wall)
    ]
    y, top = base + eave, base + eave + rise
    o = 0.3  # the eaves overhang
    v = [
        (x0 - o, y, z0 - o),
        (x1 + o, y, z0 - o),
        (x1 + o, y, z1 + o),
        (x0 - o, y, z1 + o),
        (x0 - o, top, zc),
        (x1 + o, top, zc),
    ]
    lines.append("mesh %s" % roof)
    lines.append("vertices " + "  ".join("%.2f %.2f %.2f" % p for p in v))
    lines.append("triangles 3 2 5  3 5 4  1 0 4  1 4 5  0 3 4  2 1 5")
    return lines


def main():
    rng = random.Random(1888)
    L = [
        "# Generated by art/gen_village.py - edit that and re-run, not this.",
        "# The harbour's water",
        "item cube 0 -0.6 300  1200 1 600  0.16 0.34 0.44",
        "# The land: shore, hill and headland",
        "terrain %.1f 0 %.1f  %.1f %d %d  0.3 0.5 0.2" % (X0, Z0, CELL, NX, NZ),
    ]
    hs, cs = [], []
    for j in range(NZ):
        for i in range(NX):
            x, z = X0 + i * CELL, Z0 + j * CELL
            h = height(x, z)
            hs.append(h)
            cs.append(colour(h, x, z, rng))
    for j in range(NZ):
        L.append("heights " + " ".join("%.2f" % hs[j * NX + i] for i in range(NX)))
    for j in range(NZ):
        L.append(
            "colors " + "  ".join("%.3f %.3f %.3f" % cs[j * NX + i] for i in range(NX))
        )

    L.append("# The quay wall and the front's paving")
    L.append("item cube 0 0.4 17.5  120 1.6 1.0  0.50 0.48 0.44")
    L.append("item cube 0 1.15 13.5  120 0.1 7  0.55 0.53 0.50")

    L.append("# The pier, south into the harbour, on piles; the bell tower at its end")
    L.append("item cube 6 1.25 44  3.2 0.25 52  0.45 0.33 0.22")
    for z in range(20, 70, 4):
        for x in (4.6, 7.4):
            L.append(
                "item cylinder %.1f -0.4 %d  0.35 1.6 0.35  0.25 0.20 0.15" % (x, z)
            )
    L.append("item cube 6 5.5 71  4 9 4  0.62 0.60 0.55")
    L.append("item cube 6 1.0 71  5 2 5  0.50 0.48 0.44")
    for dx in (-1.6, 1.6):
        for dz in (-1.6, 1.6):
            L.append(
                "item cube %.1f 11.5 %.1f  0.6 3 0.6  0.62 0.60 0.55"
                % (6 + dx, 71 + dz)
            )
    L.append("item cube 6 13.1 71  4.6 0.3 4.6  0.40 0.30 0.25")
    L.append("mesh 0.35 0.26 0.22")
    L.append(
        "vertices 3.7 13.25 68.7  8.3 13.25 68.7  8.3 13.25 73.3  3.7 13.25 73.3  6 15.6 71"
    )
    L.append("triangles 3 2 4  2 1 4  1 0 4  0 3 4")
    L.append("item cylinder 6 11.3 71  1.3 0.7 1.3  0.55 0.42 0.18")

    L.append("# Boats moored along the pier")
    for x, z, c in (
        (1.5, 30, "0.60 0.15 0.12"),
        (10.8, 38, "0.18 0.30 0.50"),
        (1.8, 52, "0.85 0.82 0.70"),
        (11.0, 58, "0.25 0.40 0.30"),
    ):
        L.append("item cube %.1f 0.3 %d  2.4 1.0 7  %s" % (x, z, c))
        L.append("item cube %.1f 1.3 %.1f  1.6 1.2 2.0  0.85 0.85 0.80" % (x, z - 1.0))
        L.append(
            "item cylinder %.1f 3 %.1f  0.12 2.2 0.12  0.40 0.30 0.20" % (x, z + 1.5)
        )

    L.append("# The houses along the front, and a second row up the hill")
    walls = (
        "0.85 0.82 0.74",
        "0.78 0.70 0.58",
        "0.70 0.74 0.78",
        "0.86 0.80 0.62",
        "0.72 0.56 0.48",
    )
    roofs = ("0.30 0.28 0.30", "0.45 0.24 0.18", "0.28 0.30 0.34")
    for row, (z0, z1, base) in enumerate(((2, 9.5, 1.2), (-16, -9, 2.2))):
        x = -46.0
        while x < 46:
            w = rng.uniform(6, 9)
            if row == 0 and 3 < x + w / 2 < 9:
                x += w + 1  # the gap where the pier meets the front
                continue
            L += gable(
                x,
                x + w,
                z0,
                z1,
                rng.uniform(4.0, 5.5),
                rng.uniform(2.0, 3.0),
                rng.choice(walls),
                rng.choice(roofs),
                base,
            )
            x += w + rng.uniform(0.5, 2.5)

    L.append("# The church on the hill")
    cb = height(35, -55)
    L += gable(28, 44, -61, -50, 10, 4.5, "0.66 0.64 0.58", "0.30 0.30 0.33", cb - 3.5)
    L.append("item cube 25 %.2f -55.5  6 21 6  0.62 0.60 0.55" % (cb + 7.0))
    L.append("mesh 0.30 0.30 0.33")
    t = cb + 17.5
    L.append(
        "vertices 22 %.2f -58.5  28 %.2f -58.5  28 %.2f -52.5  22 %.2f -52.5  25 %.2f -55.5"
        % (t, t, t, t, t + 6)
    )
    L.append("triangles 3 2 4  2 1 4  1 0 4  0 3 4")
    for wx in (31, 36, 41):
        L.append(
            "item cube %d %.2f -49.95  1.4 3.2 0.12  0.16 0.20 0.26" % (wx, cb + 2.5)
        )
    L.append("item cube 44.05 %.2f -55.5  0.12 4.5 2.2  0.16 0.20 0.26" % (cb + 3.0))
    L.append("item cube 25 %.2f -52.45  1.2 2.2 0.12  0.16 0.20 0.26" % (cb + 12.5))
    L.append("# Churchyard wall and stones")
    L.append(
        "item cube 36 %.2f -40  34 1.2 0.5  0.52 0.50 0.45" % (height(36, -40) + 0.4)
    )
    for k in range(40):
        gx, gz = rng.uniform(22, 50), (
            rng.uniform(-47, -42) if k % 2 else rng.uniform(-70, -63)
        )
        gy = height(gx, gz)
        L.append(
            "item cube %.2f %.2f %.2f  0.7 %.2f 0.18  0.55 0.55 0.52"
            % (gx, gy + 0.45, gz, rng.uniform(0.7, 1.1))
        )

    L.append("# The lighthouse on the point")
    lb = height(-88, 52)
    L.append("item cylinder -88 %.2f 52  4.0 7 4.0  0.92 0.92 0.88" % (lb + 6.5))
    L.append("item cylinder -88 %.2f 52  4.05 1.2 4.05  0.70 0.15 0.12" % (lb + 8))
    L.append("item cylinder -88 %.2f 52  4.6 0.25 4.6  0.20 0.20 0.20" % (lb + 13.7))
    L.append("item cylinder -88 %.2f 52  2.8 1.3 2.8  0.75 0.85 0.90 0.5" % (lb + 15.2))
    L.append("item sphere -88 %.2f 52  3.2 1.6 3.2  0.20 0.20 0.20" % (lb + 16.6))
    L.append("item cube -82 %.2f 52  5 3 4  0.92 0.92 0.88" % (lb + 1.0))

    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
